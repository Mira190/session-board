const git = (cwd, ...a) => execFileSync('git', ['-C', cwd, '-c', 'user.email=t@t', '-c', 'user.name=t', ...a], { encoding: 'utf8' }).trim();
const until = async (fn) => { for (let i = 0; i < 300; i++) { const v = await fn(); if (v) return v; await new Promise((r) => setTimeout(r, 10)); } assert.fail('timed out'); };
async function start(opts) {
  const hub = createHub({ localHost: 'laptop', github: { findPr: async () => undefined }, ...opts });
  const { port } = await hub.listen(0, '127.0.0.1');
  const base = `http://127.0.0.1:${port}`;
  const post = (path, body) => fetch(base + path, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) });
  const get = async (path) => (await fetch(base + path)).json();
  const hook = (id, cwd, name, extra = {}) => post('/ingest/claude?host=laptop', { session_id: id, cwd, hook_event_name: name, ...extra });
  return { hub, post, get, hook };
}
const repo = () => {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), 'sb-rev-')));
  git(dir, 'init', '-q', '-b', 'main');
  writeFileSync(join(dir, 'a.txt'), 'one\n'); writeFileSync(join(dir, 'gen.txt'), 'old\n'); writeFileSync(join(dir, 'wip.txt'), 'committed\n');
  git(dir, 'add', '-A'); git(dir, 'commit', '-qm', 'init');
  return dir;
};

test('what counts as checking the work', () => {
  assert.equal(checkKind('npm test -- checkout'), 'test');
  assert.equal(checkKind('pnpm run test:unit'), 'test');
  assert.equal(checkKind('cd api && pytest -q'), 'test');
  assert.equal(checkKind('npx tsc --noEmit'), 'types');
  assert.equal(checkKind('ruff check .'), 'lint');
  assert.equal(checkKind('npm run build'), 'build');
  assert.equal(checkKind('git status'), null);
  assert.equal(checkKind('echo "run the tests later"'), null);
});

test('review: changes made by shell commands are in the diff, files are marked reviewed, and a later change un-reviews them', async () => {
  const dir = repo();
  writeFileSync(join(dir, 'wip.txt'), 'the human was mid-edit before the session began\n'); // pre-existing, not the session's
  const { hub, post, get, hook } = await start();
  const key = encodeURIComponent('claude:s');
  await hook('s', dir, 'UserPromptSubmit', { prompt: 'regenerate and fix' });
  await until(() => hub.store.get('claude:s').baseline);
  await hook('s', dir, 'PreToolUse', { tool_name: 'Edit', tool_use_id: 'e1', tool_input: { file_path: join(dir, 'a.txt') } });
  writeFileSync(join(dir, 'a.txt'), 'two\n');
  writeFileSync(join(dir, 'gen.txt'), 'regenerated by a script\n'); // changed through Bash, no edit tool involved
  await hook('s', dir, 'Stop', { last_assistant_message: 'done' });

  const edited = await get(`/api/sessions/${key}/diff?scope=session`);
  assert.deepEqual(edited.files.map((f) => f.path), ['a.txt'], 'the edit-tool view misses what the script changed');
  const since = await get(`/api/sessions/${key}/diff?scope=since`);
  assert.equal(since.scope, 'since');
  assert.deepEqual(since.files.map((f) => f.path).sort(), ['a.txt', 'gen.txt'], 'the since-it-started view has both, and not what was already dirty');
  const all = await get(`/api/sessions/${key}/diff?scope=all`);
  assert.deepEqual(all.files.map((f) => f.path).sort(), ['a.txt', 'gen.txt', 'wip.txt']);
  assert.equal(git(dir, 'stash', 'list'), '', 'taking the baseline left no stash behind');
  assert.equal(git(dir, 'status', '--porcelain').split('\n').length, 3, 'and did not touch the working tree');

  const a = since.files.find((f) => f.path === 'a.txt');
  assert.deepEqual([a.viewed, a.changed_since_viewed], [false, false]);
  await post(`/api/sessions/${key}/viewed`, { path: 'a.txt', hash: a.hash });
  let now = (await get(`/api/sessions/${key}/diff?scope=since`)).files.find((f) => f.path === 'a.txt');
  assert.equal(now.viewed, true);
  writeFileSync(join(dir, 'a.txt'), 'three\n');
  now = (await get(`/api/sessions/${key}/diff?scope=since`)).files.find((f) => f.path === 'a.txt');
  assert.deepEqual([now.viewed, now.changed_since_viewed], [false, true], 'it changed after you looked');
  await post(`/api/sessions/${key}/viewed`, { path: 'a.txt', hash: null });
  assert.equal((await get(`/api/sessions/${key}/diff?scope=since`)).files.find((f) => f.path === 'a.txt').changed_since_viewed, false);
  await hub.close();
});

test('evidence, the re-entry brief and renaming', async () => {
  let t = 1_000_000;
  const { hub, post, get, hook } = await start({ now: () => t });
  const key = encodeURIComponent('claude:b');
  const row = async () => (await get('/api/sessions')).sessions[0];
  const bash = async (id, command, ok) => {
    await hook('b', '/nowhere', 'PreToolUse', { tool_name: 'Bash', tool_use_id: id, tool_input: { command } });
    await hook('b', '/nowhere', ok ? 'PostToolUse' : 'PostToolUseFailure', { tool_name: 'Bash', tool_use_id: id, tool_input: { command }, ...(ok ? { tool_response: { stdout: '' } } : { error: 'Exit code 1' }) });
  };
  await hook('b', '/nowhere', 'UserPromptSubmit', { prompt: 'Make checkout idempotent\nkeep the API stable' });
  t += 1000; await bash('t1', 'npm test', false);
  t += 1000; await hook('b', '/nowhere', 'PreToolUse', { tool_name: 'Edit', tool_use_id: 'e1', tool_input: { file_path: '/nowhere/x.ts' } });
  t += 1000; await bash('t2', 'npm test', true);
  t += 1000; await bash('l1', 'npm run lint', true);
  let s = await row();
  assert.deepEqual(s.checks.map((c) => [c.kind, c.ok]), [['test', true], ['lint', true]], 'the latest run of each command');
  assert.ok(s.last_edit_ts < s.checks[0].ts, 'tests ran after the last edit');
  t += 1000; await hook('b', '/nowhere', 'PreToolUse', { tool_name: 'Write', tool_use_id: 'e2', tool_input: { file_path: '/nowhere/y.ts' } });
  s = await row();
  assert.ok(s.last_edit_ts > s.checks.find((c) => c.kind === 'test').ts, 'then it edited again: the green run no longer covers the code');

  const looked = t;
  t += 1000; await hook('b', '/nowhere', 'PreCompact', { trigger: 'auto' });
  t += 1000; await bash('t3', 'npm test', false);
  t += 1000; await hook('b', '/nowhere', 'Notification', { notification_type: 'permission_prompt' });
  const d = await get(`/api/sessions/${key}/detail?since=${looked}`);
  assert.equal(d.brief.first_prompt, 'Make checkout idempotent\nkeep the API stable');
  assert.deepEqual([d.brief.tools, d.brief.failed_commands, d.brief.requests, d.brief.compactions, d.brief.turns], [1, 1, 1, 1, 0], 'only what happened since you looked');
  assert.equal((await get(`/api/sessions/${key}/detail`)).brief.tools, 6, 'without a marker, everything');

  await post(`/api/sessions/${key}/rename`, { title: 'Checkout idempotency' });
  await post('/ingest/event', { agent: 'claude', session_id: 'b', type: 'meta.updated', data: { title: 'an automatic title' } });
  assert.equal((await row()).title, 'Checkout idempotency', 'a name the human gave is kept');
  assert.ok(JSON.stringify(await row()).length < 2800, 'the row is still small');
  await hub.close();
});

test('two live sessions editing the same file are flagged, and a merge dry run names the conflict', async () => {
  const dir = repo();
  git(dir, 'checkout', '-qb', 'feat-a'); writeFileSync(join(dir, 'a.txt'), 'from a\n'); git(dir, 'commit', '-qam', 'a');
  git(dir, 'checkout', '-q', 'main'); git(dir, 'checkout', '-qb', 'feat-b'); writeFileSync(join(dir, 'a.txt'), 'from b\n'); git(dir, 'commit', '-qam', 'b');
  const wt = `${dir}-wt`;
  git(dir, 'worktree', 'add', '-q', wt, 'feat-a');
  const { hub, get, hook } = await start();
  await hook('a', wt, 'UserPromptSubmit', { prompt: 'change the greeting text here' });
  await hook('b', dir, 'UserPromptSubmit', { prompt: 'rework the footer layout now' });
  await until(() => hub.store.get('claude:a').branch && hub.store.get('claude:b').branch);
  const rows = async () => Object.fromEntries((await get('/api/sessions')).sessions.map((s) => [s.session_id, s]));
  assert.equal((await rows()).a.overlap, null);
  await hook('a', wt, 'PreToolUse', { tool_name: 'Edit', tool_use_id: '1', tool_input: { file_path: 'src/app.ts' } });
  await hook('b', dir, 'PreToolUse', { tool_name: 'Edit', tool_use_id: '2', tool_input: { file_path: 'src/app.ts' } });
  const r = await rows();
  assert.deepEqual([r.a.overlap.file, r.a.overlap.sessions, r.a.overlap.with], ['app.ts', 1, ['rework the footer layout now']]);
  assert.equal(r.b.overlap.files, 1);

  const d = await get(`/api/sessions/${encodeURIComponent('claude:a')}/detail`);
  assert.deepEqual(d.conflicts.map((c) => [c.branch, c.files]), [['feat-b', ['a.txt']]], 'merging the two branches would conflict in a.txt');
  assert.equal(git(dir, 'status', '--porcelain'), '', 'the dry run wrote nothing');
  await hook('b', dir, 'SessionEnd', {});
  assert.equal((await rows()).a.overlap, null, 'a finished session no longer counts');
  await hub.close();
});

test('the board will not type into a pane where the agent is no longer what is running', { skip: spawnSync('tmux', ['-V']).status !== 0 }, async () => {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), 'sb-tmux-')));
  const sock = join(dir, 'sock');
  execFileSync('tmux', ['-S', sock, 'new-session', '-d', '-s', 't', '-c', dir, 'sh']);
  const pane = execFileSync('tmux', ['-S', sock, 'display-message', '-p', '-t', 't', '#{pane_id}'], { encoding: 'utf8' }).trim();
  const { hub, post } = await start();
  const q = `&tmux_socket=${encodeURIComponent(sock)}&tmux_pane=${encodeURIComponent(pane)}`;
  await post(`/ingest/claude?host=laptop${q}`, { session_id: 't', cwd: dir, hook_event_name: 'SessionStart', source: 'startup' });
  const res = await post(`/api/sessions/${encodeURIComponent('claude:t')}/message`, { text: 'echo typed-by-the-board' });
  assert.equal(res.status, 409);
  assert.match((await res.json()).error, /would run as a shell command/);
  const screen = execFileSync('tmux', ['-S', sock, 'capture-pane', '-p', '-t', 't'], { encoding: 'utf8' });
  assert.doesNotMatch(screen, /typed-by-the-board/, 'nothing was typed');
  // A pane in some other directory is not this session's terminal either.
  execFileSync('tmux', ['-S', sock, 'respawn-pane', '-k', '-t', 't', '-c', '/', 'sleep', '30']);
  const other = await post(`/api/sessions/${encodeURIComponent('claude:t')}/message`, { text: 'hello' });
  assert.equal(other.status, 409);
  assert.match((await other.json()).error, /different directory/);
  execFileSync('tmux', ['-S', sock, 'kill-server']);
  await hub.close();
});

test('quiet hours', () => {
  const at = (h, m = 0) => new Date(2026, 0, 1, h, m);
  assert.equal(inQuietHours('22:00-08:00', at(23)), true);
  assert.equal(inQuietHours('22:00-08:00', at(7, 59)), true);
  assert.equal(inQuietHours('22:00-08:00', at(8)), false);
  assert.equal(inQuietHours('13:00-14:30', at(14)), true);
  assert.equal(inQuietHours('13:00-14:30', at(15)), false);
  assert.equal(inQuietHours('', at(3)), false);
  assert.equal(inQuietHours('nonsense', at(3)), false);
});
